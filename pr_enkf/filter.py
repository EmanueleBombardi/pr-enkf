"""
Parameter-Regularised Ensemble Kalman Filter (PR-EnKF).

Didactic implementation of the analysis step of Bombardi et al. (2026),
arXiv:2607.03571. Same mathematics as the OpenFOAM implementation, without
localisation, parameter bounds, multiple domains or clustering.

Notation
--------
alpha : (n_alpha, N)  parameter ensemble,             alpha = M_alpha psi
q     : (n_q, N)      predicted observables ensemble, q     = M_q psi
d     : (n_q,)        measurements,  C_dd = sigma_d^2 I
p     : (n_alpha,)    literature-consistent parameter values
gamma : (n_alpha,)    relative uncertainty of p
N     : ensemble size

The model state is not updated: it is regenerated by the forward model
from the updated parameters at the next iteration.
"""
import numpy as np


class ForwardModelFailure(RuntimeError):
    """Raised by a forward model when a member's parameters are non-physical."""


def analysis(alpha, q, d_pert, sigma_d, p_pert=None, gamma=None,
             inflation=1.0, eps_rel=1e-5):
    """One EnKF (p_pert=None) or PR-EnKF update of the parameter ensemble.

    d_pert : (n_q, N)      perturbed measurements       d + eps_j,  eps_j ~ N(0, C_dd)
    p_pert : (n_alpha, N)  perturbed pseudo-observations p o (1 + gamma o eta_j)
    Returns the updated parameter ensemble alpha^a, shape (n_alpha, N).
    """
    n_alpha, N = alpha.shape
    n_q = q.shape[0]
    regularise = p_pert is not None

    # 1. Predicted vector y = [M_q psi ; M_alpha psi] and observed vector d~
    if regularise:
        y = np.vstack([q, alpha])
        d_tilde = np.vstack([d_pert, p_pert])
    else:
        y = q
        d_tilde = d_pert

    # 2. Normalisation: parameters by |current mean|, observables by sigma_d
    alpha_mean = alpha.mean(axis=1)
    T = np.maximum(np.abs(alpha_mean), 1e-6)
    Lam = np.full(n_q, float(sigma_d))
    if regularise:
        Lam = np.concatenate([Lam, T])

    # 3. Normalised anomalies and ensemble covariances
    A_alpha = (alpha - alpha_mean[:, None]) / T[:, None]
    A_y = (y - y.mean(axis=1, keepdims=True)) / Lam[:, None]
    C_alpha_y = A_alpha @ A_y.T / (N - 1)
    C_yy = A_y @ A_y.T / (N - 1)

    # 4. Error covariance in normalised units: C_dd -> 1, C_pp -> gamma^2
    #    (physical units: C_dd = sigma_d^2 I, C_pp = diag((gamma * alpha_mean)^2))
    C_err = np.ones(n_q)
    if regularise:
        C_err = np.concatenate([C_err, np.asarray(gamma, float) ** 2])

    # 5. Innovation covariance, with a small jitter for numerical robustness
    S = C_yy + np.diag(C_err)
    S += eps_rel * np.linalg.norm(S, "fro") / S.shape[0] * np.eye(S.shape[0])

    # 6. Kalman gain, mapped back to physical units: K = T C_alpha_y S^-1 Lam^-1
    K = np.linalg.solve(S, C_alpha_y.T).T
    K = T[:, None] * K / Lam[None, :]

    # 7. Each parameter is pulled only towards its own literature value
    if regularise:
        K[:, n_q:] = np.diag(np.diag(K[:, n_q:]))

    # 8. Update
    alpha_a = alpha + K @ (d_tilde - y)

    # 9. Multiplicative inflation around the updated mean
    if inflation > 1.0:
        m = alpha_a.mean(axis=1, keepdims=True)
        alpha_a = m + inflation * (alpha_a - m)
    return alpha_a


def run(forward, p, gamma, d, sigma_d, n_ens=50, n_iter=30,
        regularise=True, inflation=1.05, seed=0, verbose=True):
    """Iterative EnKF / PR-EnKF parameter inference.

    forward : callable, alpha (n_alpha,) -> q (n_q,)
    Returns {"alpha": (n_it, n_alpha, N),  parameter history, including the
                                           ensemble that made the run fail
             "q":     (n_it, n_q, N),      prediction history (valid runs only)
             "failed_at": int or None}     iteration at which the run stopped
    """
    rng = np.random.default_rng(seed)
    p = np.asarray(p, float)
    gamma = np.asarray(gamma, float)
    d = np.asarray(d, float)
    n_alpha, n_q = p.size, d.size

    # Drawn once, reused at every iteration
    alpha = p[:, None] * (1 + gamma[:, None] * rng.standard_normal((n_alpha, n_ens)))
    d_pert = d[:, None] + sigma_d * rng.standard_normal((n_q, n_ens))
    p_pert = p[:, None] * (1 + gamma[:, None] * rng.standard_normal((n_alpha, n_ens)))

    hist_alpha, hist_q, failed_at = [alpha.copy()], [], None
    for it in range(n_iter + 1):
        try:
            q = np.column_stack([forward(alpha[:, j]) for j in range(n_ens)])
            if not np.all(np.isfinite(q)):
                raise ForwardModelFailure("non-finite prediction")
        except ForwardModelFailure as err:
            failed_at = it
            if verbose:
                name = "PR-EnKF" if regularise else "EnKF"
                print(f"{name}: forward model failed at iteration {it} ({err}). Stopping.")
            break
        hist_q.append(q)
        if it == n_iter:
            break
        alpha = analysis(alpha, q, d_pert, sigma_d,
                         p_pert=p_pert if regularise else None,
                         gamma=gamma, inflation=inflation)
        hist_alpha.append(alpha.copy())

    return {"alpha": np.array(hist_alpha), "q": np.array(hist_q), "failed_at": failed_at}
